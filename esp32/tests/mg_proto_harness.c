    mg_proto_disconnect(&p);
    CHECK(assist_last == 0);
    CHECK(!p.reports_state);
    calls = assist_calls;
    mg_proto_disconnect(&p);   /* not connected: nothing more */
    CHECK(assist_calls == calls);

