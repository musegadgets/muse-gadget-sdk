    static const char *const nomotor[] = { "41 03 01", "41 04 d200", "41 05 6400", "41 06 50", "3f 03", "3f 04",
                                           "3f 05", "3f 06" };
    for (size_t i = 0; i < sizeof(nomotor) / sizeof(nomotor[0]); i++) {
        clear_notes();
        write_hex(&p, MG_CH_CONTROL, nomotor[i]);
        CHECK(nnotes == 1 && notes[0].d[0] == 0x19 && notes[0].d[3] == 1 && notes[0].d[4] == 0);
    }
    CHECK(!mg_proto_haptics(&p));
    /* Every listed setting is accepted by get_settings. */
    clear_notes();
    write_hex(&p, MG_CH_CONTROL, "3f 00 02 07 0a");
    CHECK(nnotes == 1 && notes[0].d[0] == 0x3f && notes[0].len == 9);

    /* An older client that never sends assistant_state: the face ends the turn itself after playback. */
    CHECK(!p.reports_state);

    /* assistant_state: each defined state reaches the board, with no reply. */
    static const uint8_t states[] = { 2, 3, 4, 5, 0 };
    for (size_t i = 0; i < sizeof(states); i++) {
        clear_notes();
        uint8_t m[2] = { 0x83, states[i] };
        mg_proto_write(&p, MG_CH_CONTROL, m, 2);
        CHECK(nnotes == 0 && assist_last == states[i]);
    }
    int calls = assist_calls;
    write_hex(&p, MG_CH_CONTROL, "83 01");   /* 1 is reserved */
    CHECK(note_is(-1, MG_CH_CONTROL, "19 83 01 0300"));
